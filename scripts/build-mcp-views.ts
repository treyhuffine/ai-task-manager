/**
 * Bundles Ri's MCP views (`src/lib/external-ai/views/client`) into one HTML
 * document each, written as a TypeScript string next to them. The string is
 * committed, so the server, the CLI and the desktop runtime serve it with no
 * build step or file read of their own. `views.test.ts` fails when it's stale.
 *
 *   pnpm mcp-views:build
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const viewsDir = path.join(repo, 'src/lib/external-ai/views');
export const GENERATED_VIEW_FILE = path.join(viewsDir, 'tasks-view.html.ts');

const HEADER = '// Generated by `pnpm mcp-views:build` from ./client. Edit the client, then rebuild. views.test.ts fails while this is stale.\n';

export async function renderTasksViewHtml(): Promise<string> {
  const bundle = await build({
    absWorkingDir: repo, entryPoints: [path.join(viewsDir, 'client/main.ts')], bundle: true, write: false, minify: true,
    platform: 'browser', format: 'iife', target: 'es2020', legalComments: 'none', tsconfig: path.join(repo, 'tsconfig.json'),
  });
  const script = bundle.outputFiles[0].text.trim().replace(/<\/script/gi, '<\\/script');
  const css = (await fs.readFile(path.join(viewsDir, 'client/styles.css'), 'utf8')).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s*\n\s*/g, '').replace(/<\/style/gi, '<\\/style');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Ri</title><style>${css}</style></head><body><main id="root"></main><script>${script}</script></body></html>`;
}

export async function renderGeneratedViews(): Promise<string> {
  return `${HEADER}export const TASKS_VIEW_HTML = ${JSON.stringify(await renderTasksViewHtml())};\n`;
}

export async function buildMcpViews(): Promise<{ file: string; bytes: number }> {
  const source = await renderGeneratedViews();
  await fs.writeFile(GENERATED_VIEW_FILE, source);
  return { file: path.relative(repo, GENERATED_VIEW_FILE), bytes: Buffer.byteLength(source) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  buildMcpViews().then(result => console.log(`MCP views built: ${result.file} ${Math.round(result.bytes / 1024)} KiB`)).catch(error => { console.error(error); process.exitCode = 1; });
}
