import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { ContractValidator } from '@ri/app-kit/contract';
import { generateContract } from '@ri/app-kit/sdk';
import { definition } from '../src/actions.js';

const root = path.resolve(import.meta.dirname, '..');
const manifest = new ContractValidator().manifest(JSON.parse(fs.readFileSync(path.join(root, 'plugin.json'), 'utf8')));

describe('contract', () => {
  it('generates a contract that validates against plugin.json, with every example', () => {
    const contract = generateContract(definition);
    expect(() => new ContractValidator().contract(contract, manifest)).not.toThrow();
    expect(contract.actions.length).toBeLessThanOrEqual(100);
  });

  it('names every action the People spec lists, plus the common actions', () => {
    const names = new Set(definition.actions.map((action) => action.name));
    const required = [
      'list_people', 'get_person', 'search_people', 'save_person', 'list_organizations', 'get_organization', 'save_organization', 'save_affiliation', 'list_interactions', 'link_interaction', 'preview_company_attribution', 'apply_company_attribution',
      'save_note', 'list_commitments', 'review_commitment', 'review_fact', 'get_briefing', 'request_briefing', 'get_relationship_context',
      'list_views', 'save_view', 'list_lists', 'save_list', 'update_list_members', 'bulk_update_records',
      'list_pipelines', 'save_pipeline', 'save_pipeline_stages', 'list_opportunities', 'get_opportunity', 'save_opportunity', 'move_opportunity',
      'resolve_identity', 'merge_people', 'merge_organizations', 'undo_merge',
      'open_view', 'describe_view_context', 'create_scope', 'list_sources', 'run_background_step', 'sync_step', 'enrich_step', 'preview_import', 'apply_import', 'create_follow_up',
      'list_scopes', 'revoke_scope', 'continue_import',
    ];
    for (const name of required) expect(names.has(name), name).toBe(true);
  });

  it('keeps source management, scopes, merges, navigation and pipeline structure user only', () => {
    const userOnly = ['create_scope', 'list_scopes', 'revoke_scope', 'list_sources', 'configure_source', 'pause_source', 'delete_source_data', 'set_extraction', 'continue_import', 'preview_import', 'apply_import', 'export_records',
      'save_navigation', 'save_pipeline', 'save_pipeline_stages', 'merge_people', 'merge_organizations', 'undo_merge', 'resolve_identity', 'apply_company_attribution', 'delete_record', 'save_exclusion'];
    for (const name of userOnly) expect(definition.actions.find((action) => action.name === name)!.audience, name).toEqual(['user']);
    for (const name of ['run_background_step', 'sync_step', 'enrich_step']) {
      const action = definition.actions.find((item) => item.name === name)!;
      expect(action.audience).toEqual(['schedule']);
      expect(action.timeoutMs).toBe(40000);
      expect(action.effect).toBe('app_write');
      expect(action.retry).toBe('idempotent');
    }
    for (const action of definition.actions) {
      if (action.effect === 'read') expect(action.retry, action.name).toBe('read_safe');
      expect(action.examples.length, action.name).toBeGreaterThan(0);
    }
  });

  it('matches the committed contract.json generated by packaging', () => {
    const file = path.join(root, 'contract.json');
    expect(fs.existsSync(file), 'Run pnpm --filter ri-people package to generate contract.json').toBe(true);
    const workflows = JSON.parse(fs.readFileSync(file, 'utf8')).workflows;
    expect(JSON.parse(fs.readFileSync(file, 'utf8'))).toEqual(JSON.parse(JSON.stringify(generateContract(definition, workflows))));
  });

  it('copy avoids long dashes and semicolons in user-visible descriptions', () => {
    for (const action of definition.actions) {
      expect(action.description, action.name).not.toMatch(/[–—]/);
      expect(action.description, action.name).not.toMatch(/;/);
    }
  });
});
