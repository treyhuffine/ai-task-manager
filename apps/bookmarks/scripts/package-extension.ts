/**
 * The browser extension as a zip: written to release/ for the Chrome Web Store,
 * and embedded in the app so its Connect screen can offer the download. The zip
 * is deterministic, so a test can check the embedded copy matches the folder.
 */
import fs from "node:fs";
import path from "node:path";
import { deflateRawSync } from "node:zlib";

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(data: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of data) crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

export function listFiles(dir: string, prefix = ""): string[] {
  return fs.readdirSync(path.join(dir, prefix), { withFileTypes: true })
    .filter((entry) => !entry.name.startsWith("."))
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => (entry.isDirectory() ? listFiles(dir, path.join(prefix, entry.name)) : [path.join(prefix, entry.name)]));
}

/** A minimal zip: deflated entries, a fixed timestamp, sorted names. */
export function buildZip(dir: string): Buffer {
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  // 2026-01-01 00:00, so the same files always make the same bytes.
  const date = ((2026 - 1980) << 9) | (1 << 5) | 1;
  for (const relative of listFiles(dir)) {
    const name = Buffer.from(relative.split(path.sep).join("/"));
    const data = fs.readFileSync(path.join(dir, relative));
    const packed = deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(8, 8);
    local.writeUInt16LE(0, 10);
    local.writeUInt16LE(date, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(packed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    locals.push(local, name, packed);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(0, 12);
    central.writeUInt16LE(date, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(packed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += local.length + name.length + packed.length;
  }
  const directory = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(listFiles(dir).length, 8);
  end.writeUInt16LE(listFiles(dir).length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}

export const generatedSource = (version: string, zip: Buffer) =>
  `/** Generated by \`pnpm --filter ri-bookmarks extension:package\` from extension/. Do not edit. */\nexport const EXTENSION_PACKAGE = {\n  version: ${JSON.stringify(version)},\n  base64: ${JSON.stringify(zip.toString("base64"))},\n} as const;\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.dirname, "package-extension.ts")) {
  const root = path.resolve(import.meta.dirname, "..");
  const extension = path.join(root, "extension");
  const { version } = JSON.parse(fs.readFileSync(path.join(extension, "manifest.json"), "utf8")) as { version: string };
  const zip = buildZip(extension);
  const release = path.join(root, "release");
  fs.mkdirSync(release, { recursive: true });
  const target = path.join(release, `ri-bookmarks-extension-${version}.zip`);
  fs.writeFileSync(target, zip);
  fs.writeFileSync(path.join(root, "src/extension-package.generated.ts"), generatedSource(version, zip));
  console.log(`${target} (${zip.length} bytes)`);
}
