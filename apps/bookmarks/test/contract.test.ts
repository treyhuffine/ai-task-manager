import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { ContractValidator } from "@ri/app-kit/contract";
import { generateContract } from "@ri/app-kit/sdk";
import { definition } from "../src/actions.js";

const root = path.resolve(import.meta.dirname, "..");
function workflows() {
  const dir = path.join(root, "skills");
  return fs.readdirSync(dir).sort().flatMap((name) => {
    const file = `skills/${name}/SKILL.md`;
    if (!fs.existsSync(path.join(root, file))) return [];
    const front = /^---\n([\s\S]*?)\n---/.exec(fs.readFileSync(path.join(root, file), "utf8"))?.[1] ?? "";
    return [{ name: /^name:\s*(.+)$/m.exec(front)?.[1]?.trim() ?? name, description: /^description:\s*(.+)$/m.exec(front)![1].trim(), file }];
  });
}

describe("contract", () => {
  const validator = new ContractValidator();
  const manifest = validator.manifest(JSON.parse(fs.readFileSync(path.join(root, "plugin.json"), "utf8")));
  const contract = generateContract(definition, workflows());
  const audience = (name: string) => contract.actions.find((action) => action.name === name)!.audience;

  it("validates against plugin.json, including every example", () => {
    expect(() => validator.contract(contract, manifest)).not.toThrow();
    expect(() => validator.contract(contract, { ...manifest, extensions: { "com.ri": { ...manifest.extensions["com.ri"], requests: { ...manifest.extensions["com.ri"].requests, clientActions: ["run_background_step"] } } } })).toThrow(/client action/);
    expect(() => validator.contract(contract, { ...manifest, extensions: { "com.ri": { ...manifest.extensions["com.ri"], requests: { ...manifest.extensions["com.ri"].requests, clientActions: ["no_such_action"] } } } })).toThrow(/client action/);
  });

  it("keeps management and destructive actions with the owner and background work with the schedule", () => {
    for (const name of ["delete_bookmark", "create_scope", "preview_import", "apply_import", "upload_import_part", "export_bookmarks", "list_connections", "connect_client", "disconnect_client", "get_extension_package", "save_bookmarks", "save_link", "describe_connection"]) expect(audience(name)).toEqual(["user"]);
    expect(audience("run_background_step")).toEqual(["schedule"]);
    expect(contract.actions.find((action) => action.name === "run_background_step")).toMatchObject({ effect: "app_write", retry: "idempotent", timeoutMs: 40000 });
  });

  it("lets a client key reach only actions that cannot read saved links", () => {
    expect(manifest.extensions["com.ri"].requests.clientActions).toEqual(["save_bookmarks", "save_link", "describe_connection"]);
    for (const name of manifest.extensions["com.ri"].requests.clientActions!) {
      const output = JSON.stringify(contract.actions.find((action) => action.name === name)!.outputSchema);
      for (const field of ["title", "url", "note", "tags", "items", "record"]) expect(output, `${name} output`).not.toContain(`"${field}"`);
    }
  });

  it("registers the bookmark entity with a deep link", () => {
    expect(contract.entities.map((entity) => [entity.type, entity.openPath])).toEqual([["bookmark", "/bookmarks/{id}"]]);
    expect(Object.keys(contract.contexts)).toEqual(["ui://ri-bookmarks/main.html"]);
  });

  it("uses copy without long dashes or semicolons in descriptions", () => {
    for (const action of contract.actions) {
      expect(action.description).not.toMatch(/[—–]/);
      expect(action.description).not.toContain(";");
    }
  });

  it("matches the committed contract.json generated by packaging", () => {
    expect(JSON.parse(fs.readFileSync(path.join(root, "contract.json"), "utf8"))).toEqual(JSON.parse(JSON.stringify(contract)));
  });
});
