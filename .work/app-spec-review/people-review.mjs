const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:1500,height:1100}})
const errors = [], external = [], checks = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (!request.url().startsWith('file:')) external.push(request.url()) })
const url = 'file:///Users/agent/ai-task-manager/docs/mockups/people-app.html'
const tab = label => page.locator('.crm-main-tabs').getByRole('button',{name:label,exact:true}).click()
async function fresh() { await page.goto(url) }
async function enable(which) {
  await page.getByRole('button',{name:'+ Add view',exact:true}).click()
  await page.locator(`[data-enable="${which}"]`).click()
}
async function layout(name) {
  const widths = [320,360,390,760,1100,1500]
  for (const width of widths) {
    await page.setViewportSize({width,height:1100})
    const size = await page.evaluate(()=>({inner:innerWidth,scroll:document.documentElement.scrollWidth}))
    assert.ok(size.scroll <= size.inner + 1,`${name} overflow at ${width}: ${JSON.stringify(size)}`)
    checks.push({name,width})
  }
  await page.setViewportSize({width:1500,height:1100})
}
