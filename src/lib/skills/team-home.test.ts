it('shares the normal draft, hash-checked editor and install operations, with live owner writes and member reads', async () => {
  const owner = await teamTrpc(fixture.owner.token.plaintext), member = await teamTrpc(fixture.member.token.plaintext);
  q.saveTeamAiSettings({ enabled: false }, fixture.owner.member.id);
  const made = await owner.skills.create.mutate({ body: { name: 'weekly-review', description: 'Review shared weekly work and identify decisions.', body: 'Read the shared tasks. Summarize decisions requested by the member.' } });
  expect(made.skill).toMatchObject({ ref: 'draft:weekly-review', canWriteGlobal: false, editable: true });
  expect(JSON.stringify(made)).not.toContain(fixture.home.root);
  expect((await member.skills.list.query({})).skills).toEqual([]);
  await expect(member.skills.RefGet.query({ params: { ref: made.skill.ref } })).rejects.toThrow(/unavailable/);
  await expect(member.skills.create.mutate({ body: { name: 'member-installed' } })).rejects.toThrow(/cannot perform/);
  const installed = await owner.skills.moveRefPost.mutate({ params: { ref: made.skill.ref }, body: { to: 'ri' } });
  const read = await member.skills.RefGet.query({ params: { ref: installed.skill.ref } });
  expect(read.skill).toMatchObject({ ref: 'ri:weekly-review', editable: false, canWriteGlobal: false });
  expect((await member.skills.list.query({})).skills.map(skill => skill.ref)).toEqual(['ri:weekly-review']);
  await expect(member.skills.RefPut.mutate({ params: { ref: read.skill.ref }, body: { body: 'Change another member’s execution policy.', baseHash: read.skill.hash } })).rejects.toThrow(/cannot perform/);
  const saved = await owner.skills.RefPut.mutate({ params: { ref: read.skill.ref }, body: { body: 'Updated shared instructions.', baseHash: read.skill.hash } });
  expect(saved.skill.body).toBe('Updated shared instructions.');
  await expect(owner.skills.RefPut.mutate({ params: { ref: read.skill.ref }, body: { body: 'Stale replacement.', baseHash: read.skill.hash } })).rejects.toThrow(/changed/i);
  const headers = { authorization: 'Bearer ' + fixture.member.token.plaintext, 'content-type': 'application/json', [API_PROTOCOL_HEADER]: String(API_PROTOCOL) };
  const raw = await serveTeam('http://team.test/api/skills', { method: 'POST', headers, body: JSON.stringify({ name: 'forged-member' }) });
  expect(raw.status).toBe(403);
  q.revokeApiKey(fixture.owner.key.id, 'Owner signed out');
  await expect(owner.skills.moveRefPost.mutate({ params: { ref: installed.skill.ref }, body: { to: 'draft' } })).rejects.toThrow();
  expect((await getSkillView(installed.skill.ref))?.body).toBe('Updated shared instructions.');
});

it('never discovers host/global or coincidentally local project skills and refuses linked files and library roots', async () => {
  const host = path.join(fixture.home.root, 'host-private'); fs.mkdirSync(path.join(host, '.claude/skills/private-skill'), { recursive: true });
  const secret = path.join(host, 'private.md'); fs.writeFileSync(secret, 'PRIVATE-SKILL-CANARY');
  fs.writeFileSync(path.join(host, '.claude/skills/private-skill/SKILL.md'), 'PRIVATE-SKILL-CANARY');
  vi.spyOn(os, 'homedir').mockReturnValue(host);
  q.createWorkspace({ name: 'Coincidentally local path', slug: 'local', cwd: host, isGit: false });
  expect(await skillsOverview()).toMatchObject({ skills: [], projects: [], canWriteGlobal: false });
  const owner = await teamTrpc(fixture.owner.token.plaintext);
  for (const ref of ['global:private-skill', 'project:local:private-skill']) await expect(owner.skills.RefGet.query({ params: { ref } })).rejects.toThrow(/unavailable/);
  await expect(owner.skills.create.mutate({ body: { name: 'outside', location: 'global' } })).rejects.toThrow(/library/);
  const library = path.join(fixture.home.root, 'skills'); fs.mkdirSync(path.join(library, 'linked-file'), { recursive: true });
  fs.symlinkSync(secret, path.join(library, 'linked-file/SKILL.md'));
  expect((await skillsOverview()).skills).toEqual([]);
  expect(await getSkillView('ri:linked-file')).toBeNull();
  const valid = await owner.skills.create.mutate({ body: { name: 'safe-skill', description: 'Safe shared file boundary checks.', body: 'Keep supporting files in the skill.' } });
  fs.symlinkSync(host, path.join(fixture.home.root, 'skill-drafts/safe-skill/references'));
  await expect(owner.skills.RefPut.mutate({ params: { ref: valid.skill.ref }, body: { files: [{ path: 'references/private.md', content: 'Unauthorized overwrite' }], baseHash: valid.skill.hash } })).rejects.toThrow(/symbolic links/);
  fs.rmSync(library, { recursive: true }); fs.symlinkSync(path.join(host, '.claude/skills'), library);
  await expect(owner.skills.create.mutate({ body: { name: 'root-escape', location: 'ri', description: 'Cannot install outside the shared Home.', body: 'Keep the Home boundary.' } })).rejects.toThrow(/inside the team’s folder/);
  expect(fs.existsSync(path.join(host, '.claude/skills/root-escape'))).toBe(false);
  expect(fs.readFileSync(secret, 'utf8')).toBe('PRIVATE-SKILL-CANARY');
});

it('recycles shared skill sessions without cancelling accepted work, while drafts and retries leave it alone', async () => {
  const { setSkillSessionControlForTests } = await import('./manage');
  const recycle = vi.fn(async () => {});
  setSkillSessionControlForTests({ recycleWhenIdle: recycle, close: async () => {} });
  const owner = await teamTrpc(fixture.owner.token.plaintext);
  const installed = await owner.skills.create.mutate({ body: { name: 'shared-policy', location: 'ri', description: 'Shared execution instructions.', body: 'Earlier instructions.' } });
  const chat = q.createChatSession({ harness: 'codex', model: 'gpt-6.1-sol', type: 'orchestration', surfaceKind: q.TEAM_CHAT_SURFACE, workspaceId: fixture.workspace.id, deviceId: q.getHome()!.hostDeviceId, createdByMemberId: fixture.member.member.id });
  let calls = 0;
  setTeamAiRunnerForTests(async input => { calls++; return new Promise(resolve => input.signal!.addEventListener('abort', () => resolve({ status: 'cancelled' }), { once: true })); });
  const send = (id: string) => sendToTeamAi({ chatId: chat.id, memberId: fixture.member.member.id, requestingApiKeyId: fixture.member.key.id, clientSendId: id, text: 'Use the installed shared skill.' });
  const running = await send('before-skill-change'); await vi.waitFor(() => expect(calls).toBe(1));
  const queued = await send('waiting-skill-change');
  const draft = await owner.skills.create.mutate({ body: { name: 'still-drafting' } });
  await owner.skills.RefPut.mutate({ params: { ref: draft.skill.ref }, body: { body: 'Work in progress.', baseHash: draft.skill.hash } });
  expect(q.getTeamChatTurn(running.turn.id)?.status).toBe('running'); expect(q.getTeamChatTurn(queued.turn.id)?.status).toBe('queued');
  const input = { params: { ref: installed.skill.ref }, body: { body: 'Current instructions.', baseHash: installed.skill.hash } };
  await owner.skills.RefPut.mutate(input);
  expect(q.getTeamChatTurn(running.turn.id)?.status).toBe('running'); expect(q.getTeamChatTurn(queued.turn.id)?.status).toBe('queued');
  expect(recycle).toHaveBeenCalledWith(chat.id);
  const recycled = recycle.mock.calls.length;
  await owner.skills.RefPut.mutate(input);
  expect(q.getTeamChatTurn(running.turn.id)?.status).toBe('running');
  expect(recycle).toHaveBeenCalledTimes(recycled);
  setSkillSessionControlForTests(null);
});

it('shared skill create and hash-checked saves succeed after an idle close failure while the old handle stays blocked', async () => {
  const executor = await import('@/lib/executor/adapter');
  const { setSkillSessionControlForTests } = await import('./manage');
  setSkillSessionControlForTests(null);
  const owner = await teamTrpc(fixture.owner.token.plaintext);
  const chat = q.createChatSession({ harness: 'codex', model: 'gpt-6.1-sol', type: 'orchestration', surfaceKind: q.TEAM_CHAT_SURFACE, workspaceId: fixture.workspace.id, deviceId: q.getHome()!.hostDeviceId, createdByMemberId: fixture.member.member.id });
  const close = vi.fn(async () => { throw new Error('Provider shutdown failed'); });
  executor._cacheHarnessSession(chat.id, { close } as unknown as import('@agentex/agent').AgentSession);
  const made = await owner.skills.create.mutate({ body: { name: 'restart-policy', location: 'ri', description: 'Keep saved shared instructions.', body: 'First shared instruction.' } });
  const saved = await owner.skills.RefPut.mutate({ params: { ref: made.skill.ref }, body: { body: 'Second shared instruction.', baseHash: made.skill.hash } });
  const savedAgain = await owner.skills.RefPut.mutate({ params: { ref: saved.skill.ref }, body: { body: 'Third shared instruction.', baseHash: saved.skill.hash } });
  expect((await getSkillView(savedAgain.skill.ref))?.body).toBe('Third shared instruction.');
  expect(close).toHaveBeenCalledOnce(); expect(executor.hasUnconfirmedClose(chat.id)).toBe(true); expect(executor.hasHarnessSession(chat.id)).toBe(true);
  close.mockResolvedValueOnce(undefined as never);
  expect(await executor.close(chat.id)).toMatchObject({ closed: true });
  expect(executor.hasUnconfirmedClose(chat.id)).toBe(false);
});
