import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { afterEach, beforeAll, beforeEach, expect, it, vi } from 'vitest';
import { createTeamExecutionFixture } from '@/test/fixtures/team-execution';
import { preloadTeamRoutes, serveTeam, teamTrpc } from '@/test/fixtures/team-home';
import * as q from '@/lib/db/queries';
import { API_PROTOCOL, API_PROTOCOL_HEADER } from '@/lib/releases/api-contract';
let fixture: Awaited<ReturnType<typeof createTeamExecutionFixture>>;
beforeAll(preloadTeamRoutes, 120_000);
beforeEach(async () => { fixture = await createTeamExecutionFixture(); vi.stubGlobal('fetch', serveTeam); });
afterEach(async () => { vi.restoreAllMocks(); await fixture.cleanup(); vi.unstubAllGlobals(); });
it('lets the owner use ordinary server folders while members read them and cannot configure them', async () => {
  const owner = await teamTrpc(fixture.owner.token.plaintext), member = await teamTrpc(fixture.member.token.plaintext);
  vi.spyOn(os, 'homedir').mockReturnValue(fixture.home.root);
  const params = { id: fixture.workspace.id };
  expect(await owner.fs.browseGet.query({ query: { path: fixture.home.root } })).toBeDefined();
  await expect(member.fs.browseGet.query({ query: { path: fixture.home.root } })).rejects.toMatchObject({ data: { httpStatus: 403 } });
  const folder = path.join(fixture.home.root, 'linked'); fs.mkdirSync(folder);
  await owner.workspaces.foldersPost.mutate({ params, body: { alias: 'shared-reference', folder, deviceId: q.getHome()!.hostDeviceId, readOnly: true } });
  const read = await member.workspaces.foldersGet.query({ params });
  expect(JSON.stringify(read)).toContain(folder);
  await expect(member.workspaces.foldersPost.mutate({ params, body: { alias: 'Unauthorized', folder, deviceId: q.getHome()!.hostDeviceId } })).rejects.toMatchObject({ data: { httpStatus: 403 } });
  await expect(owner.workspaces.foldersPost.mutate({ params, body: { alias: 'Other device', folder, deviceId: 'another-device' } })).rejects.toMatchObject({ data: { httpStatus: 403 } });
});
it('keeps browser voice preferences private with AI off and refuses host transcription', async () => {
  const owner = await teamTrpc(fixture.owner.token.plaintext), member = await teamTrpc(fixture.member.token.plaintext);
  q.saveTeamAiSettings({ enabled: false }, fixture.owner.member.id);
  expect(await member.userState.update.mutate({ body: { voiceAutoSend: false, voiceModel: 'web/speech-recognition' } })).toMatchObject({ voiceAutoSend: false });
  expect(await owner.userState.list.query({})).toMatchObject({ voiceAutoSend: null });
  expect(await member.userState.list.query({})).toMatchObject({ voiceAutoSend: false });
  await expect(member.userState.update.mutate({ body: { defaultModel: 'not-an-owner' } })).rejects.toMatchObject({ data: { httpStatus: 403 } });
  await expect(member.transcribe.status.query({})).rejects.toMatchObject({ data: { httpStatus: 403 } });
  const headers = { authorization: `Bearer ${fixture.member.token.plaintext}`, [API_PROTOCOL_HEADER]: String(API_PROTOCOL) };
  const form = new FormData(); form.set('file', new Blob(['fixture audio'], { type: 'audio/webm' }), 'voice.webm');
  const result = await serveTeam('http://team.test/api/transcribe', { method: 'POST', headers, body: form });
  expect(result.status).toBe(403); expect(await result.json()).toMatchObject({ code: 'team_boundary' });
  q.removeMember(fixture.member.member.id);
  expect((await serveTeam('http://team.test/api/transcribe', { headers })).status).toBe(401);
});
