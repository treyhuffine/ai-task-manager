import { afterEach, beforeAll, beforeEach, expect, it, vi } from 'vitest';
import * as q from '@/lib/db/queries';
import { createTeamExecutionFixture } from '@/test/fixtures/team-execution';
import { installFakeHarness, type FakeHarness } from '@/test/fixtures/fake-harness';
import { preloadTeamRoutes, serveTeam, teamTrpc } from '@/test/fixtures/team-home';
import { nativeTeamTools } from '@/lib/team/mcp/native-tools';
import { settledTeamAi, stopTeamAiWork } from '@/lib/team/ai/chat';
import { closeAllSessions, _resetExecutorState } from '@/lib/runner/local-runner';
let fixture: Awaited<ReturnType<typeof createTeamExecutionFixture>>, fake: FakeHarness;
let member: Awaited<ReturnType<typeof teamTrpc>>, owner: Awaited<ReturnType<typeof teamTrpc>>;
let source: ReturnType<typeof q.createExecutionWithChat>;
beforeAll(preloadTeamRoutes, 120_000);
beforeEach(async () => {
  fixture = await createTeamExecutionFixture(); vi.stubGlobal('fetch', serveTeam); fake = installFakeHarness('claude');
  q.saveTeamAiSettings({ harness: 'claude' }, fixture.owner.member.id);
  member = await teamTrpc(fixture.member.token.plaintext); owner = await teamTrpc(fixture.owner.token.plaintext);
  await owner.results.setCapabilities.mutate({ handoffsEnabled: true, aiReviewEnabled: true });
  source = q.createExecutionWithChat({ workspaceId: fixture.workspace.id, createdByMemberId: fixture.member.member.id, surfaceKind: q.TEAM_CHAT_SURFACE, harness: 'claude', label: 'Shared work' });
  q.createPlacement({ executionId: source.execution.id, deviceId: q.getHome()!.hostDeviceId, startReason: 'created', worktreePath: fixture.workspace.cwd });
});
afterEach(async () => { await stopTeamAiWork({}, 'Fixture ended.'); await settledTeamAi(); await closeAllSessions(); _resetExecutorState(); fake.restore(); await fixture.cleanup(); vi.unstubAllGlobals(); });
it('shares saved results and member decisions with AI off, with member-scoped retry identities', async () => {
  await expect(member.results.setCapabilities.mutate({ handoffsEnabled: false })).rejects.toThrow(/owner/);
  const input = { requestId: 'same-local-request', body: 'Saved shared work', sourceChatSessionId: source.session.id };
  const first = await member.results.save.mutate(input), second = await owner.results.save.mutate(input);
  expect(second.resultId).not.toBe(first.resultId);
  q.saveTeamAiSettings({ enabled: false }, fixture.owner.member.id);
  expect(await member.results.save.mutate(input)).toMatchObject({ resultId: first.resultId, replayed: true });
  await owner.results.decide.mutate({ id: first.resultId, requestId: 'accepted', disposition: 'accepted' });
  expect(q.getWorkResult(first.resultId)?.reviews[0].actorMemberId).toBe(fixture.owner.member.id);
  q.removeMember(fixture.member.member.id); await expect(member.results.get.query({ id: first.resultId })).rejects.toThrow(/401/);
});
it('prepares and reports through the ordinary serialized runner and retains the requesting member', async () => {
  const entered = Promise.withResolvers<void>(), finish = Promise.withResolvers<void>();
  fake.onTurn(async () => { entered.resolve(); await finish.promise; });
  const preparation = await member.results.prepare.mutate({ requestId: 'prepare-shared-work', sourceChatSessionId: source.session.id });
  await entered.promise;
  const turn = q.runningTeamChatTurn(source.session.id)!;
  const report = nativeTeamTools(turn.id, fixture.member.member.id).find(tool => tool.name === 'report_result')!;
  const saved = await report.run({ request_id: 'prepare-shared-work', body: 'Completed shared work' });
  expect(saved.ok).toBe(true);
  const resultId = (saved as { result: { result_id: string } }).result.result_id;
  expect(q.getWorkResult(resultId)?.result.actorMemberId).toBe(fixture.member.member.id);
  finish.resolve(); await settledTeamAi(); expect(q.getRun(preparation.runId!)?.status).toBe('completed');
  expect((await report.run({ request_id: 'stale-report', body: 'After completion' })).ok).toBe(false);
});
it('uses the common read-only reviewer and refuses all ordinary follow-ups before accepting them', async () => {
  const entered = Promise.withResolvers<void>(); fake.onTurn(async () => { entered.resolve(); await new Promise(() => {}); });
  const saved = await member.results.save.mutate({ requestId: 'review-target', body: 'Inspect this exact work', sourceChatSessionId: source.session.id });
  const requested = await member.results.requestReview.mutate({ id: saved.resultId, requestId: 'review-shared', harness: 'claude' });
  await entered.promise;
  const review = q.getWorkResultAiReview(requested.reviewId)!;
  const tools = nativeTeamTools(q.runningTeamChatTurn(review.reviewerSessionId!)!.id, fixture.member.member.id);
  expect(tools.map(tool => tool.name)).toEqual(['get_result', 'report_result_review']);
  await expect(owner.sessions.messagesPost.mutate({ params: { id: review.reviewerSessionId! }, body: { content: 'Implement this' } })).rejects.toThrow(/background reviewer/);
  expect(q.listTeamChatTurns(review.reviewerSessionId!)).toHaveLength(1);
  expect(fake.latest().ctx.config?.planMode).toBe(true);
  await owner.results.cancelReview.mutate({ reviewId: review.id });
});
